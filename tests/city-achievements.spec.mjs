import{test,expect}from'@playwright/test';
import{build}from'esbuild';
import{readFileSync}from'node:fs';
const script=readFileSync('bitburner-zh-cn.user.js','utf8');
const fixture=(await build({entryPoints:['tests/city-achievements-fixture.jsx'],bundle:true,write:false,format:'iife',define:{'process.env.NODE_ENV':'"development"'}})).outputFiles[0].text;
const host='#bitburner-zh-cn-overlay';
const nav=(p,name)=>p.locator('.MuiDrawer-root').getByRole('button',{name,exact:true});
test.beforeEach(async({page})=>{
 await page.setContent('<style>body{font:16px monospace;padding:12px}.MuiModal-root{position:fixed;inset:10%;background:#eee;border:1px solid;padding:25px;overflow:auto}button{font-size:16px}h6{font-size:18px}</style><div id="root"></div>');
 await page.evaluate(()=>{window.GM_getValue=(k,v)=>v;window.secondaryErrors=[];window.addEventListener('error',e=>window.secondaryErrors.push(e.message));});
 await page.addScriptTag({content:fixture});
 await expect(nav(page,'City')).toBeVisible();
 await page.addScriptTag({content:script});
 await expect(nav(page,'城市')).toBeVisible();
});
test('city names are bilingual, map stays intact, location clicks retain original identity and restore',async({page})=>{
 await expect(page.locator('main')).toContainText('Sector-12（第12区）');
 await expect(page.locator('#map')).toHaveText('U -- H -- G');
 await page.locator('#map span').hover();
 await expect(page.locator(host+' section')).toContainText('Rothman University（罗斯曼大学）');
 await page.getByRole('button',{name:'Rothman University（罗斯曼大学）',exact:true}).click();
 expect(await page.evaluate(()=>window.selectedLocation)).toBe('Rothman University');
 await expect(page.locator('h4')).toHaveText('Rothman University（罗斯曼大学）');
 await page.getByRole('button',{name:'学习计算机科学（免费）',exact:true}).click();
 expect(await page.evaluate(()=>window.cityAction)).toBe('Rothman University');
 await page.locator(host).getByRole('button',{name:'中文：开'}).click();
 await expect(page.locator('h4')).toHaveText('Rothman University');
 await expect(page.getByRole('button',{name:'Return to World',exact:true})).toBeVisible();
});
