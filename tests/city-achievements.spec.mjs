test('late offline report on another page translates duration and income without changing data or dismiss controls',async({page})=>{
 await nav(page,'属性').click();
 await page.evaluate(()=>window.secondary.setModal('offline'));
 const dialog=page.getByRole('dialog');
 await expect(dialog).toContainText('离线时长 1 天 2 小时 3 分钟 4 秒。离线期间：');
 await expect(dialog).toContainText('你的脚本获得了 $12.500m');
 await expect(dialog).toContainText('1.250k 哈希');
 await expect(dialog).toContainText('123.456 声望，已分配到你的各个派系');
 await page.evaluate(()=>{window.secondary.setElapsed('2 seconds');window.secondary.setMoney('$21.900m')});
 await expect(dialog).toContainText('离线时长 2 秒。离线期间：');
 await expect(page.locator('#money')).toHaveText('$21.900m');
 await expect(page.locator('#terminal')).toHaveText('Offline for 1 day. While you were offline:');
 await page.locator(host).getByRole('button',{name:'中文：开'}).click();
 await expect(dialog).toContainText('Offline for 2 seconds. While you were offline:');
 await expect(dialog).toContainText('Your scripts generated $21.900m');
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await expect(dialog).toHaveCount(0);
});
test('join button fits Chinese in narrow flex rows and modal; layout restores on toggle, hover and React label change',async({page})=>{
 await nav(page,'派系').click();
 const list=page.locator('#join-list');
 await expect(list).toHaveAttribute('data-bitburner-zh-fit','join');
 const fit=async el=>el.evaluate(b=>({w:b.getBoundingClientRect().width,overflow:b.scrollWidth>b.clientWidth,wrap:getComputedStyle(b).whiteSpace,shrink:getComputedStyle(b).flexShrink}));
 expect(await fit(list)).toMatchObject({overflow:false,wrap:'nowrap',shrink:'0'});
 expect((await fit(list)).w).toBeGreaterThan(30);
 await page.locator(host).getByRole('button',{name:'显示：直接'}).click();
 await expect(list).not.toHaveAttribute('data-bitburner-zh-fit');
 expect(await list.evaluate(b=>b.style.width)).toBe('30px');
 await page.locator(host).getByRole('button',{name:'显示：悬停'}).click();
 await expect(list).toHaveAttribute('data-bitburner-zh-fit','join');
 await list.click();
 await expect(list).toHaveText('详情');
 await expect(list).not.toHaveAttribute('data-bitburner-zh-fit');
 expect(await page.evaluate(()=>window.factionAction)).toBe('CyberSec');
 await page.evaluate(()=>{window.secondary.setPage('Stats');window.secondary.setModal('invitation')});
 const modal=page.locator('#join-modal');
 await expect(modal).toHaveAttribute('data-bitburner-zh-fit','join');
 expect(await fit(modal)).toMatchObject({overflow:false});
 await page.getByRole('dialog').screenshot({path:'output/playwright/local-join-width.png'});
 await page.locator(host).getByRole('button',{name:'中文：开'}).click();
 await expect(modal).not.toHaveAttribute('data-bitburner-zh-fit');
 expect(await page.evaluate(()=>[...document.head.querySelectorAll('style')].some(s=>s.textContent.includes('data-bitburner-zh-fit')))).toBe(false);
 expect(await modal.evaluate(b=>b.getBoundingClientRect().width)).toBe(30);
 await modal.click();
 expect(await page.evaluate(()=>window.factionAction)).toBe('CyberSec');
 expect(await page.evaluate(()=>window.secondaryErrors)).toEqual([]);
});
