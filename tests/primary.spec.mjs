import{test,expect}from'@playwright/test';
import{build}from'esbuild';
import{readFileSync}from'node:fs';
const script=readFileSync('bitburner-zh-cn.user.js','utf8');
const fixture=(await build({entryPoints:['tests/primary-fixture.jsx'],bundle:true,write:false,format:'iife',define:{'process.env.NODE_ENV':'"development"'}})).outputFiles[0].text;
const host='#bitburner-zh-cn-overlay';
const toggle=p=>p.locator(host).getByRole('button',{name:'中文：开'});
test.beforeEach(async({page})=>{
 await page.setContent('<style>body{padding:12px}p{white-space:pre-wrap}button{padding:6px}main{max-width:780px}.MuiModal-root{position:fixed;inset:8%;background:#eee;padding:20px;border:2px solid #555;z-index:10}</style><div id="root"></div>');
 await page.evaluate(()=>{window.GM_getValue=(k,v)=>v;window.primaryErrors=[];window.addEventListener('error',e=>window.primaryErrors.push(e.message));});
 await page.addScriptTag({content:fixture});
 await expect(page.locator('h4')).toHaveText('Factions');
 await page.evaluate(()=>{window.originalRoot=document.getElementById('root').innerHTML;window.originalRemaining=document.getElementById('remaining').firstChild;});
 await page.addScriptTag({content:script});
 await expect(page.locator('h4')).toHaveText('派系');
});
